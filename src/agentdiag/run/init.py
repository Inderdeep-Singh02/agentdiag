"""`agentdiag init`: the files that make a directory a Workspace, and a Target in it.

D39 asks for a Manifest skeleton, a sample Suite and a gitignore entry, and — when no
Adapter is named — a scaffold pointing at the shipped toy Target, so the first `agentdiag
run` works before anyone has written an Adapter or found a key.

Since ADR-0013 the root is a Workspace of Targets (phase-6 decision 4): `init` with no
`.agentdiag/` under the root creates one holding the Target `default` (or the one `--target`
names) at `.agentdiag/targets/<slug>/`, and `init --target <slug>` on an existing Workspace
adds that Target beside the others. A root still in the Phase 4 spelling (a Manifest directly
under `.agentdiag/`) is refused with the move that fixes it, never rearranged here: a command
that moved an author's files unasked would be the surprise this module exists to avoid.

Two rules shape everything here:

- **Nothing that already exists is overwritten.** An existing Target directory stops the
  command with exit 3 naming the path, because a Manifest is hand-edited from its first
  day and silently replacing one would lose work nothing recorded.
- **`--force` rewrites the scaffold and never the Runs.** A Run is immutable and is output,
  not source (ADR-0005 §2): re-scaffolding a Target is not permission to delete one. Nor
  the calibration notes: `judge_notes.md` (ticket 05) is written when absent and left
  alone when present, because notes are what an author learned about judging the Target,
  and a starter file is no replacement for them. The same holds for `redaction.yaml`, the
  Target's local list of names a Change record never carries (ADR-0015 §4), which `init`
  writes as an empty starter and gitignores.

After the Target's files, `init` writes the Orientation page, its two import files and the
vocabulary copy at the root through `orientation.write_orientation` (ADR-0016 §1-§3), whose
own rule is the same: a page or an import file the user wrote keeps every byte, and only the
marked Targets table is agentdiag's to regenerate. They are listed among the created paths
only when written, so a second `init --target` names `AGENTS.md` because its table changed.

The text itself lives in `templates.py`, which the checked-in examples are rendered from
(`examples/toy/`, `examples/workspace/`), so they stay the truth of what this command writes.
"""

