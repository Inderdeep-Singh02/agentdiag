def test_show_prints_the_judges_cost_beside_the_targets(tmp_path: Path) -> None:
    root = target_root(tmp_path)
    run(root, CANCEL)

    shown = show(root, CANCEL)

    # Two Judge calls, the Eval's and the Diagnosis's (D24), each priced on its Span. The
    # cancel Trial's Judge answers are captured (ticket 21, decision 41), so their cost is
    # read from the Spans rather than written here; the Target's is authored.
    judgement = only_run(root) / "trials" / CANCEL / "1" / "judgement.jsonl"
    costs = [
        event["attributes"]["llm.cost.total"]
        for event in map(json.loads, judgement.read_text(encoding="utf-8").splitlines())
        if event["type"] == "span/end"
    ]
    assert len(costs) == 2
    assert f"Cost target $0.006900 · judge ${round(sum(costs), 6):.6f}" in shown
    assert f"${costs[0]:.6f}" in next(line for line in shown.splitlines() if "judge-1" in line)


