def test_the_whole_example_suite_replays_from_one_scoped_recording(tmp_path: Path) -> None:
    """Decision 19: every Scenario's Trial walks its own view of one file."""
    root = target_root(tmp_path)

    result = run(root, *EVERY_SCENARIO)

    assert result.exit_code == 1, result.stdout
    last = next(line for line in result.stdout.splitlines() if "pass rate" in line)
    # Ticket 04's 24 mechanical Scores, the cancel Scenario's prompt_adherence — the
    # Judge's fail on rule 3 (`tests/stories.py`) — ticket 05's ten: goal,
    # data_grounding, data_query, tool_choice, the three of the authored-lists Scenario,
    # and one per guardrail rule, of which no-refund-timing fails — and ticket 06's two
    # passes over the adaptive Scenario, `expect_tools_order` and its `goal`.
    assert last.startswith(
        "pass 33  fail 4  incomplete 0  unverifiable 2  invalid 0  pass rate 89% (33 of 37)"
    )
    assert "not run 0" in last
    for scenario in EVERY_SCENARIO:
        assert f"{scenario}  trial 1" in result.stdout
        terminations = [
            json.loads(line)["termination"]
            for line in (only_run(root) / "trials" / scenario / "1" / "trace.jsonl")
            .read_text(encoding="utf-8")
            .splitlines()
            if json.loads(line)["type"] == "trace/end"
        ]
        # A Scenario of literal Turns completes; the adaptive one ends on its criterion.
        assert terminations == ["stop_when" if scenario == ADAPTIVE else "completed"]


def test_every_mechanical_score_stores_its_evidence_fidelity_and_code(tmp_path: Path) -> None:
    root = target_root(tmp_path)

    run(root, WHERE)

    for score in scores(root, WHERE):
        assert score["evidence"], score
        assert score["fidelity"] == "instrumented"
        assert score["source"]["kind"] == "mechanical"
        assert score["source"]["code"].startswith("agentdiag.eval.")


def test_a_latency_score_stores_its_value_threshold_and_direction(tmp_path: Path) -> None:
    """ADR-0003 §5: a later threshold change never re-interprets a stored Score."""
    root = target_root(tmp_path)

    run(root, WHERE)

    by_eval = {score["eval"]: score for score in scores(root, WHERE)}
    tool = by_eval["tool_latency"]
    response = by_eval["response_latency"]
    assert tool["threshold"] == {"max_ms": 1000}
    assert response["threshold"] == {"max_ms": 30000}
    assert tool["direction"] == response["direction"] == "minimize"
    assert isinstance(tool["value"], float) and tool["value"] <= 1000
    assert isinstance(response["value"], float) and response["value"] <= 30000


