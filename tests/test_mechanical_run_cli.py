def test_an_empty_manifest_list_gives_every_scenario_a_passing_inherited_score(
    tmp_path: Path,
) -> None:
    root = target_root(tmp_path)
    edit_manifest(root, forbidden_phrases=[])

    run(root, STATUS, GREETING)

    for scenario in (STATUS, GREETING):
        (inherited,) = [s for s in scores(root, scenario) if s["eval"] == "forbidden_phrases"]
        assert inherited["verdict"] == "pass"
        assert "The Manifest declares no forbidden phrases" in inherited["rationale"]
    summary = json.loads((only_run(root) / "run.json").read_text(encoding="utf-8"))["scenarios"]
    for entry in summary:
        assert {
            "eval": "forbidden_phrases",
            "id": None,
            "inherited": True,
            "params": {},
            "threshold": None,
        } in entry["evals"]


