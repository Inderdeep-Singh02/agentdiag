"""Seam 1: the example Suite's mechanical Evals through `agentdiag run` and `show`, in replay.

The Scenarios under the example Suite's `EXAMPLE_ONLY` marker exercise every mechanical
Eval against the toy Target. They replay from one recording whose every line is scoped to
its Scenario (phase-5 decision 19), generated by `scripts/record_fixtures.py --scripted`,
so each test here selects what it needs and the rest of the file stays invisible to it.
Each test reads what a user can observe: the summary, the exit code, `scores.json`,
`run.json`, `show`. No model is called.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

import yaml
from typer.testing import CliRunner

from agentdiag.cli import app
from agentdiag.model.prices import PRICE_TABLE_VERSION

REPO = Path(__file__).resolve().parents[1]
EXAMPLE = REPO / "examples" / "toy"
SUITE_RECORDING = REPO / "tests" / "fixtures" / "recordings" / "toy-orders.jsonl"

CANCEL = "cancel-processing-order"
WHERE = "where-is-shipped-order"
LOOKUP_THEN_CANCEL = "lookup-then-cancel"
STATUS = "status-question-is-not-a-cancel"
UNSEEN = "lookup-with-unseen-arguments"
GREETING = "greeting-calls-no-tool"
JUDGED = [
    "delivered-order-cannot-be-cancelled",
    "order-details-come-from-the-lookup",
    "status-lookup-asks-for-the-named-order",
    "cancel-looks-up-then-cancels",
    "authored-lists-decide-without-a-judge",
    "cancel-with-a-promised-refund-date",
]
"""The Scenarios ticket 05 added for the judged Evals; the last is the guardrails Suite's."""

ADAPTIVE = "cancel-without-the-order-number"
"""The example's adaptive Scenario (ticket 06): a scripted opener and a simulated tail."""

EVERY_SCENARIO = [CANCEL, WHERE, LOOKUP_THEN_CANCEL, STATUS, UNSEEN, GREETING, *JUDGED, ADAPTIVE]

runner = CliRunner()


def target_root(tmp_path: Path) -> Path:
    root = tmp_path / "toy"
    shutil.copytree(EXAMPLE, root, ignore=shutil.ignore_patterns("runs"))
    return root


def run(root: Path, *scenarios: str, extra: tuple[str, ...] = ()) -> Any:
    selection = [argument for scenario in scenarios for argument in ("--scenario", scenario)]
    return runner.invoke(
        app,
        ["run", "--root", str(root), *selection, *extra, "--replay", str(SUITE_RECORDING)],
    )


def only_run(root: Path) -> Path:
    (run_dir,) = (root / ".agentdiag" / "targets" / "toy-order-desk" / "runs").iterdir()
    return run_dir


def scores(root: Path, scenario: str) -> list[dict[str, Any]]:
    path = only_run(root) / "trials" / scenario / "1" / "scores.json"
    return list(json.loads(path.read_text(encoding="utf-8"))["scores"])


def verdicts(root: Path, scenario: str) -> dict[str, tuple[str, str | None]]:
    return {score["eval"]: (score["verdict"], score["reason"]) for score in scores(root, scenario)}


def edit_manifest(root: Path, **fields: Any) -> None:
    path = root / ".agentdiag" / "targets" / "toy-order-desk" / "manifest.yaml"
    manifest = yaml.safe_load(path.read_text(encoding="utf-8"))
    manifest.update(fields)
    path.write_text(yaml.safe_dump(manifest), encoding="utf-8")


def show(root: Path, scenario: str) -> str:
    result = runner.invoke(app, ["show", only_run(root).name, scenario, "--root", str(root)])
    assert result.exit_code == 0, result.output
    return str(result.stdout)


