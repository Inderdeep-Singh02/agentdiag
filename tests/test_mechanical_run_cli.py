def test_show_prints_unpriced_for_a_model_the_price_table_does_not_price(tmp_path: Path) -> None:
    """A Trace an Adapter wrote for an unpriced model: no cost attribute, so `unpriced`."""
    root = target_root(tmp_path)
    run(root, GREETING)
    trace = only_run(root) / "trials" / GREETING / "1" / "trace.jsonl"
    lines = []
    for line in trace.read_text(encoding="utf-8").splitlines():
        event = json.loads(line)
        if event["type"] == "span/end" and event["span_id"] == "llm_call-1":
            for name in [key for key in event["attributes"] if key.startswith("llm.cost.")]:
                event["attributes"].pop(name)
            event["attributes"]["gen_ai.response.model"] = "claude-mystery-1"
        lines.append(json.dumps(event, ensure_ascii=False))
    trace.write_text("\n".join(lines) + "\n", encoding="utf-8")

    shown = show(root, GREETING)

    assert "unpriced" in next(line for line in shown.splitlines() if "llm_call-1" in line)
    assert "Cost target unpriced" in shown
    assert "$0.000000" not in shown


def test_a_run_recorded_before_cost_was_stamped_still_reads(tmp_path: Path) -> None:
    """A Phase 4 `run.json` has no `price_table`; it reads as None and `show` still renders."""
    from agentdiag.run.record import RunRecord

    root = target_root(tmp_path)
    run(root, GREETING)
    path = only_run(root) / "run.json"
    record = json.loads(path.read_text(encoding="utf-8"))
    del record["price_table"]
    path.write_text(json.dumps(record), encoding="utf-8")

    assert RunRecord.model_validate(record).price_table is None
    assert "Scores" in show(root, GREETING)
